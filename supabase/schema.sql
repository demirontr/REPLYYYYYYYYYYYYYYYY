create table universities (
  id int generated by default as identity primary key,
  name text not null,
  country text not null,
  city text not null
);

create table companies (
  id int generated by default as identity primary key,
  name text not null,
  sector text,
  description text,
  logo_url text,
  fields text[] not null default '{}',
  website text
);

create table users (
  id int generated by default as identity primary key,
  name text not null,
  role text not null check (role in ('student', 'company', 'university')),
  university_id int references universities(id),
  company_id int references companies(id),
  department text,
  year int,
  interests text[] not null default '{}',
  academic_status text,
  gpa numeric,
  xp int not null default 0,
  elo int not null default 1200,
  created_at timestamptz not null default now()
);

create table courses (
  id int generated by default as identity primary key,
  university_id int not null references universities(id),
  code text not null,
  name text not null,
  year int
);

create table questions (
  id int generated by default as identity primary key,
  course_id int not null references courses(id),
  topic text not null,
  difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
  prompt text not null,
  choices jsonb not null check (jsonb_typeof(choices) = 'array' and jsonb_array_length(choices) = 4),
  correct_index int not null check (correct_index between 0 and 3),
  explanation text not null,
  source text,
  parent_question_id int references questions(id),
  status text not null default 'approved' check (status in ('approved', 'pending_review'))
);

create table test_sessions (
  id int generated by default as identity primary key,
  user_id int not null references users(id) on delete cascade,
  course_id int not null references courses(id),
  kind text not null check (kind in ('daily', 'retry', 'duel', 'tournament')),
  ref_id int,                       -- duels.id / tournaments.id
  question_ids int[] not null,      -- question order for this session
  date date not null,               -- Europe/Rome day
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  total_xp int not null default 0
);
-- one daily test per user, course and day
create unique index test_sessions_daily_once on test_sessions (user_id, course_id, date) where kind = 'daily';

create table answers (
  id int generated by default as identity primary key,
  session_id int not null references test_sessions(id) on delete cascade,
  user_id int not null references users(id) on delete cascade,
  question_id int not null references questions(id),
  chosen_index int not null check (chosen_index between 0 and 3),
  is_correct boolean not null,
  time_ms int not null,
  xp_awarded int not null default 0,
  created_at timestamptz not null default now(),
  unique (session_id, question_id)
);
create index answers_user on answers (user_id);

create table locations (
