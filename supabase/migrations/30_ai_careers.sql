-- Every agent call (input, output, success) for debugging and as evidence for the jury (PLAN.md §9).
create table if not exists ai_logs (
  id int generated by default as identity primary key,
  agent text not null,
  user_id int references users(id) on delete set null,
  ok boolean not null,
  attempt int not null default 1,
  ms int,
  input text,
  output text,
  error text,
  created_at timestamptz not null default now()
);
create index if not exists ai_logs_agent_time on ai_logs (agent, created_at desc);

create index if not exists recommendations_user_time on recommendations (user_id, created_at desc);
create index if not exists recommendation_feedback_rec on recommendation_feedback (recommendation_id);
create index if not exists analysis_reports_user_time on analysis_reports (user_id, created_at desc);
create index if not exists notifications_user_time on notifications (user_id, read, created_at desc);
create index if not exists follows_company on follows (company_id);
create index if not exists questions_parent on questions (parent_question_id);

-- One rating per user per recommendation (re-rating updates it).
create unique index if not exists recommendation_feedback_once on recommendation_feedback (recommendation_id, user_id);

-- New job post -> one notification per follower, in a single statement.
create or replace function notify_followers(p_job int) returns int
language sql as $$
  with j as (
    select jp.id, jp.title, jp.kind, jp.company_id, c.name as company_name
    from job_posts jp join companies c on c.id = jp.company_id
    where jp.id = p_job
  ), ins as (
    insert into notifications (user_id, type, payload)
    select f.user_id, 'job_post',
           jsonb_build_object('job_post_id', j.id, 'company_id', j.company_id, 'company_name', j.company_name, 'title', j.title, 'kind', j.kind)
    from follows f join j on f.company_id = j.company_id
    returning 1
  )
  select count(*)::int from ins;
$$;
